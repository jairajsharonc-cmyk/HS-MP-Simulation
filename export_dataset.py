#!/usr/bin/env python3
"""Export the data behind the paper as plain CSV files (the 'dataset' for the Data-availability statement).

Usage:  python export_dataset.py --in results --out data
Creates:
  data/per_step_metrics.csv   one row per (strategy, seed, step): all metrics        (10 seeds x 4 strategies x 300 steps = 12,000 rows)
  data/per_seed_summary.csv   one row per (strategy, seed): metrics averaged over steps (40 rows)
  data/request_traces.csv     the synthetic request workload per (seed, step)         (3,000 rows)
  data/DATA_DICTIONARY.md     description of every column
"""
import argparse, os, shutil
import numpy as np, pandas as pd
from hsmp import Config
from hsmp.workload import Workload
from hsmp.lstm import MLPopularCaching
from hsmp.simulator import _streams

ap = argparse.ArgumentParser()
ap.add_argument("--in", dest="inp", default="results"); ap.add_argument("--out", default="data")
a = ap.parse_args(); os.makedirs(a.out, exist_ok=True)

z = np.load(os.path.join(a.inp, "timeseries.npz"))
cols, seeds = list(z["columns"]), list(z["seeds"])
rows = []
for s in ["HH", "HQ", "MH", "MQ"]:
    arr = z[s]                                   # (seeds, steps, metrics)
    for i, seed in enumerate(seeds):
        df = pd.DataFrame(arr[i], columns=cols)
        df.insert(0, "step", np.arange(1, len(df) + 1)); df.insert(0, "seed", int(seed)); df.insert(0, "strategy", s)
        rows.append(df)
pd.concat(rows).to_csv(os.path.join(a.out, "per_step_metrics.csv"), index=False)
shutil.copy(os.path.join(a.inp, "per_seed_summary.csv"), a.out)

cfg = Config(); tr = []
for seed in seeds:
    _, r_work, *_ = _streams(int(seed)); w = Workload(cfg, r_work)
    for t in range(1, cfg.total_steps + 1):
        v, c = w.next()
        tr.append(dict(seed=int(seed), step=t, video_id=v, chunk_idx=c,
                       chunk_id=MLPopularCaching.encode(v, c, cfg.chunks_per_video)))
pd.DataFrame(tr).to_csv(os.path.join(a.out, "request_traces.csv"), index=False)

open(os.path.join(a.out, "DATA_DICTIONARY.md"), "w").write("""# Data dictionary
All data are generated by the HS-MP simulator (synthetic; no external dataset or personal data).
Seeds 0-9, 300 steps per run, strategies: HH, HQ, MH, MQ (caching H/M = FIFO/LSTM, ABR H/Q = throughput/Q-learning).

## per_step_metrics.csv
strategy, seed, step (1-300) | latency_ms: chunk delivery latency | energy_j: energy per chunk, Eq.(1) |
available: 1 if chunk located | stall_s: stall seconds | switch: 1 if quality changed | cache_hit: 1 if served within 0-1 hops |
bitrate_mbps: delivered bitrate | hops: overlay hops (NaN if unavailable)

## per_seed_summary.csv
Per (strategy, seed) means of the above over the 300 steps (+ stall_ratio). These are the inputs to Table 2 and the paired t-tests of Table 3.

## request_traces.csv
seed, step, video_id (0-29), chunk_idx (0-179), chunk_id = video_id*180 + chunk_idx. Identical across the four strategies for a given seed.
""")
print("Dataset written to", a.out)
